// Символ NOVA (брендбук Concept G): ровная (вертикальная) тонкая звезда +
// орбитальное кольцо, слегка наклонённое (-8°), со «спутником-планеткой».
// Saturn-эффект: задняя дуга кольца идёт ЗА звездой, передняя — поверх.
// По последним правкам: звезда крупнее (растянута внутри viewBox),
// кольцо поднято на ~15 px и сужено на ~20 px по диаметру.
export function NovaStar({ size = 40, className = '' }: { size?: number; className?: string }) {
  // Наклон кольца -8° вокруг (100,102) + смещение на 28 ед. вниз
  // (38 было → поднято на 10 ед. ≈ 15 px).
  const ring = 'translate(0 28) rotate(-8 100 102)';
  // Эллипс орбиты: центр (100,102), rx 77, ry 15 — диаметр сужен на ~20 px.
  const backArc = 'M 23 102 A 77 15 0 0 1 177 102';
  const frontArc = 'M 177 102 A 77 15 0 0 1 23 102';
  // Звезда: 104 ед. по X (48–152), 220 ед. по Y (-6–214) — стороны сужены
  // на ~20 px (13 ед.), кольцо и вертикаль не тронуты.
  const star =
    'M100 -6 Q105 94 152 104 Q105 114 100 214 Q95 114 48 104 Q95 94 100 -6 Z';
  return (
    <svg
      className={`nova-star ${className}`}
      width={size}
      height={size}
      viewBox="0 0 200 200"
      fill="none"
      aria-hidden="true"
    >
      {/* Задняя половина орбиты (наклонённая, опущенная) — за звездой */}
      <g transform={ring}>
        <path d={backArc} stroke="#E2E8F0" strokeWidth="2.4" fill="none" />
      </g>
      {/* Звезда (тонкая, вертикальная, шире и ниже) */}
      <path d={star} fill="#F59E0B" />
      {/* Передняя половина орбиты + спутник (наклонённые, смещённые) — поверх звезды */}
      <g transform={ring}>
        <path d={frontArc} stroke="#E2E8F0" strokeWidth="2.4" fill="none" />
        {/* Спутник: точка точно на новом эллипсе (rx 77, ry 15, t≈35°) */}
        <circle cx="163.1" cy="110.6" r="5.5" fill="#FFFFFF" />
      </g>
    </svg>
  );
}
