// Символ NOVA — по задумке nova-logo/Frame 1.svg:
// 1) БОЛЬШОЙ острый ромб (4-лучевая звезда, 2:1) — задаёт размеры всей звезды;
// 2) Меньшие ромбы со скруглениями во внутрь — накладываются в центр,
//    давая приятную (мягкую) форму к сердцевине (эффект звезды-новы).
// Кольцо-орбита (тонкое, горизонтальное) и спутник — без изменений.
// Откат к предыдущему лого: git checkout 65e9a8f -- src/components/ui/NovaStar.tsx
export function NovaStar({ size = 40, className = '' }: { size?: number; className?: string }) {
  // Кольцо: горизонтальный эллипс, центр (100,102), rx 70, ry 13.5
  // (сужено ещё на ~20 px по диаметру).
  const backArc = 'M 30 102 A 70 13.5 0 0 1 170 102'; // верхняя дуга — за звездой
  const frontArc = 'M 170 102 A 70 13.5 0 0 1 30 102'; // нижняя дуга — поверх звезды
  // БОЛЬШОЙ острый ромб (основа, задаёт размер): 4 вершины + pinch между лучами.
  // Звезда всего на ~1.375× вокруг (100,102) (1.25×, затем ещё 1.10×).
  // Кольцо при этом НЕ трогаем.
  const cross =
    'M100 -26.7 L106.88 93.75 L164.63 102 L106.88 110.25 L100 231.25 L93.12 110.25 L35.38 102 L93.12 93.75 Z';
  // МЕЛКИЙ ромб со скруглениями во внутрь — тот же масштаб звезды (~1.375×).
  const spark =
    'M100 62.4 Q104.62 94.96 130.25 102 Q104.62 109.04 100 141.6 Q95.38 109.04 69.75 102 Q95.38 94.96 100 62.4 Z';
  // Спутник на переднем (нижнем) витке кольца: точка эллипса (rx 70, ry 13.5) при t≈30°
  // → x = 100 + 70·cos30 ≈ 160.6, y = 102 + 13.5·sin30 ≈ 108.75.
  return (
    <svg
      className={`nova-star ${className}`}
      width={size}
      height={size}
      viewBox="0 0 200 200"
      fill="none"
      aria-hidden="true"
    >
      <defs>
        <radialGradient id="nova-star-grad" cx="100" cy="102" r="96" gradientUnits="userSpaceOnUse">
          <stop offset="0" stopColor="#FFF6D8" />
          <stop offset="0.35" stopColor="#FCD34D" />
          <stop offset="1" stopColor="#F59E0B" />
        </radialGradient>
      </defs>
      {/* Задняя (верхняя) половина орбиты — за звездой. Кольцо и шарик:
          наклон −8° + сдвиг вниз на 20 ед. (~30 px на hero-размере 300 px) */}
      <g transform="translate(0 20) rotate(-8 100 102)">
        <path d={backArc} stroke="#E2E8F0" strokeWidth="2.4" fill="none" />
      </g>
      {/* БОЛЬШОЙ острый ромб (основа) с градиентом */}
      <path d={cross} fill="url(#nova-star-grad)" />
      {/* МЕЛЬЧЙШИЙ ромб со скруглениями во внутрь — приятная форма к центру,
          теперь того же градиента, что и основной (единый цвет) */}
      <path d={spark} fill="url(#nova-star-grad)" />
      {/* Передняя (нижняя) половина орбиты + спутник — поверх звезды (те же наклон и сдвиг) */}
      <g transform="translate(0 20) rotate(-8 100 102)">
        <path d={frontArc} stroke="#E2E8F0" strokeWidth="2.4" fill="none" />
        <circle cx="160.6" cy="108.75" r="5.5" fill="#FFFFFF" />
      </g>
    </svg>
  );
}
