// Символ NOVA — по задумке nova-logo/Frame 1.svg:
// 1) БОЛЬШОЙ острый ромб (4-лучевая звезда, 2:1) — задаёт размеры всей звезды;
// 2) Меньшие ромбы со скруглениями во внутрь — накладываются в центр,
//    давая приятную (мягкую) форму к сердцевине (эффект звезды-новы).
// Кольцо-орбита (тонкое, горизонтальное) и спутник — без изменений.
// Откат к предыдущему лого: git checkout 65e9a8f -- src/components/ui/NovaStar.tsx
export function NovaStar({ size = 40, className = '' }: { size?: number; className?: string }) {
  // Кольцо: горизонтальный эллипс, центр (100,102), rx 77, ry 15.
  const backArc = 'M 23 102 A 77 15 0 0 1 177 102'; // верхняя дуга — за звездой
  const frontArc = 'M 177 102 A 77 15 0 0 1 23 102'; // нижняя дуга — поверх звезды
  // БОЛЬШОЙ острый ромб (основа, задаёт размер): 4 вершины, вертикаль 2× горизонтали.
  // Вершины: верх (100,8), право (147,102), низ (100,196), лево (53,102).
  // Между лучами — неглубокие «зажмычки» (pinch) для эффекта звезды-новы:
  //   неглубоко справа-вверху (105,96), неглубоко справа-внизу (105,108), и зеркала.
  const cross =
    'M100 8 L105 96 L147 102 L105 108 L100 196 L95 108 L53 102 L95 96 Z';
  // МЕЛКИЙ ромб со скруглениями во внутрь (приятная форма к центру):
  // высота ~36% от большого, кривые Q тянут углы внутрь.
  const spark =
    'M100 68 Q104 96 126 102 Q104 108 100 136 Q96 108 74 102 Q96 96 100 68 Z';
  // Спутник на переднем (нижнем) витке кольца: точка эллипса при t≈30°
  // → x = 100 + 77·cos30 ≈ 166.7, y = 102 + 15·sin30 ≈ 109.5.
  return (
    <svg
      className={`nova-star ${className}`}
      width={size}
      height={size}
      viewBox="0 0 200 200"
      fill="none"
      aria-hidden="true"
    >
      <defs>
        <radialGradient id="nova-star-grad" cx="100" cy="102" r="96" gradientUnits="userSpaceOnUse">
          <stop offset="0" stopColor="#FFF6D8" />
          <stop offset="0.35" stopColor="#FCD34D" />
          <stop offset="1" stopColor="#F59E0B" />
        </radialGradient>
      </defs>
      {/* Задняя (верхняя) половина орбиты — за звездой */}
      <path d={backArc} stroke="#E2E8F0" strokeWidth="2.4" fill="none" />
      {/* БОЛЬШОЙ острый ромб (основа) с градиентом */}
      <path d={cross} fill="url(#nova-star-grad)" />
      {/* Меньший ромб со скруглениями во внутрь — приятная форма к центру */}
      <path d={spark} fill="#FFF3C4" opacity="0.92" />
      {/* Передняя (нижняя) половина орбиты + спутник — поверх звезды */}
      <path d={frontArc} stroke="#E2E8F0" strokeWidth="2.4" fill="none" />
      <circle cx="166.7" cy="109.5" r="5.5" fill="#FFFFFF" />
    </svg>
  );
}
